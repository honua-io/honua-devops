namespace Honua.DevOps.Agent.Operations.Troubleshooting;

internal static class FaultCatalog
{
    internal static IReadOnlyList<FaultScenario> All => Scenarios;

    internal static FaultScenario? Resolve(string scenarioId)
    {
        return Scenarios.FirstOrDefault(scenario =>
            string.Equals(scenario.Id, scenarioId, StringComparison.OrdinalIgnoreCase));
    }

    internal static IReadOnlyList<FaultScenario> ByCategory(FaultCategory category)
    {
        return Scenarios.Where(scenario => scenario.Category == category).ToArray();
    }

    internal static IReadOnlyList<FaultScenario> ByCloud(string cloud)
    {
        return Scenarios.Where(scenario =>
            scenario.TargetCloud.Contains(cloud, StringComparison.OrdinalIgnoreCase)).ToArray();
    }

